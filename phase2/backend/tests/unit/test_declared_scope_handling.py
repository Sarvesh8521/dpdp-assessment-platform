@pytest.mark.asyncio
async def test_runtime_config_does_not_mutate_declared_scope(mock_session, mock_client):
    """
    Test that runtime configuration values (e.g. data.config.integrations, properties)
    do NOT automatically get injected into the scope sheet evidence.
    """
    scope = DeclaredScope(
        search_console_properties=["https://explicitly-declared.com"],
        marketing_platforms=["Declared Platform"]
    )
    
    config = AssessmentConfig(
        integrations=["ga4", "github", "some_undecided_runtime_platform"],
        properties=["https://runtime-property.com"],
        scope=scope
    )

    data = AssessmentCreate(
        client_id=mock_client.id,
        config=config
    )

    from collections import defaultdict
    service = AssessmentService(mock_session, mock_client.id)
    
    class MockObligations(dict):
        def __init__(self, default_uuid):
            self.default_uuid = default_uuid
            
        def __contains__(self, key):
            return True
            
        def __getitem__(self, key):
            return self.default_uuid
            
    # Use a mock dict to handle any obligation code generated by graceful degradation
    def_uuid = uuid.uuid4()
    service._ensure_obligations_seeded = AsyncMock(return_value=MockObligations(def_uuid))
    
    # Mock adapter execution to avoid side effects
    service._run_adapter = AsyncMock(return_value=[])
    
    import unittest.mock
    
    with unittest.mock.patch('app.services.assessment_service.run_reconciliation') as mock_recon:
        mock_recon.return_value = []
        
        # Run the assessment creation which builds the scope_sheet evidence
        await service.create_assessment(data, uuid.uuid4())
        
        # Verify that the scope sheet evidence ONLY contains the explicitly declared properties and platforms
        assert mock_recon.call_count == 1
        evidence_by_source = mock_recon.call_args[0][0]
        
        scope_evidence = evidence_by_source.get("scope_sheet", [])
        
        assert len(scope_evidence) > 0, "Scope sheet evidence must be generated"
        
        for ev in scope_evidence:
            if ev.source == "scope_sheet:search_console_properties":
                props = ev.raw_metadata.get("search_console_properties", [])
                assert "https://explicitly-declared.com" in props
                assert "https://runtime-property.com" not in props, "Runtime property leaked into declared scope!"
                
            elif ev.source == "scope_sheet:marketing_platforms":
                platforms = ev.raw_metadata.get("marketing_platforms", [])
                assert "Declared Platform" in platforms
                assert "ga4" not in platforms, "Runtime integration leaked into declared scope platforms!"
                assert "some_undecided_runtime_platform" not in platforms, "Runtime integration leaked into declared platforms!"
